import { parseEntityRef } from '@backstage/catalog-model';
import type { TailnetGraph } from './graph';
import {
  describeFlow,
  describeGrant,
  flowsOf,
  grantAllows,
  grantPorts,
  isServiceGrant,
  type Flow,
  type Grant,
  type Policy,
} from './policy';
import { formatPort, isWildcardPort } from './ports';

export interface RenderOptions {
  /** Cluster Resource name -> the tag of the Tailscale operator on it. */
  clusterTagOwners: Record<string, string>;
  /** Owners of every generated tag, besides the operator. */
  defaultTagOwners: string[];
  /** Where the live policy comes from, for the report. */
  basePolicyUrl: string;
  /** Where the catalog lives, for links in the report. */
  catalogUrl?: string;
}

export interface GeneratedGrant extends Grant {
  /** The catalog edges this grant comes from: "consumer → api". */
  from: string[];
  ip: string[];
}

export type GrantStatus = 'match' | 'broad' | 'new';
export type DeclaredStatus = 'declared' | 'partial' | 'missing';

export interface Rendered {
  grants: GeneratedGrant[];
  tagOwners: Record<string, string[]>;
  tests: Array<{ src: string; accept: string[] }>;
  policyText: string;
  report: string;
  summary: Record<GrantStatus | DeclaredStatus | 'grants', number>;
}

/** component:default/backstage -> component:backstage */
export function shortRef(ref: string): string {
  const { kind, namespace, name } = parseEntityRef(ref);
  return namespace === 'default' ? `${kind}:${name}` : ref;
}

function grantsFromGraph(graph: TailnetGraph): GeneratedGrant[] {
  const byKey = new Map<string, GeneratedGrant>();
  for (const edge of graph.edges) {
    const src = [...edge.src].sort();
    const dst = [...edge.dst].sort();
    const ip = edge.ports.map(formatPort).sort();
    const key = JSON.stringify([src, dst, ip]);
    const from = `${shortRef(edge.consumer)} → ${shortRef(edge.api)}`;
    const grant = byKey.get(key);
    if (grant) grant.from.push(from);
    else byKey.set(key, { src, dst, ip, from: [from] });
  }
  return [...byKey.values()].sort((a, b) =>
    describeGrant(a).localeCompare(describeGrant(b)),
  );
}

function tagOwnersFor(
  graph: TailnetGraph,
  grants: GeneratedGrant[],
  base: Policy,
  options: RenderOptions,
): Record<string, string[]> {
  // The clusters each tag shows up on, to find its operator.
  const clustersOfTag = new Map<string, Set<string>>();
  const note = (tags: string[], clusters: string[]) => {
    for (const tag of tags.filter(t => t.startsWith('tag:'))) {
      const set = clustersOfTag.get(tag) ?? new Set();
      clusters.forEach(c => set.add(parseEntityRef(c).name));
      clustersOfTag.set(tag, set);
    }
  };
  for (const edge of graph.edges) {
    note(edge.src, edge.srcClusters);
    note(edge.dst, edge.dstClusters);
  }
  const owners: Record<string, string[]> = {};
  const tags = new Set(grants.flatMap(g => [...g.src, ...g.dst]));
  for (const tag of [...tags].filter(t => t.startsWith('tag:')).sort()) {
    if (base.tagOwners?.[tag]) continue;
    const operators = [...(clustersOfTag.get(tag) ?? [])]
      .map(c => options.clusterTagOwners[c])
      .filter(Boolean);
    owners[tag] = [...new Set([...options.defaultTagOwners, ...operators])];
  }
  return owners;
}

function testsFor(grants: GeneratedGrant[]) {
  // Tailscale policy tests can't name Tailscale Services, and a test without
  // proto checks TCP: tag destinations on TCP (or any-protocol) ports only.
  return grants.flatMap(grant => {
    const accept = grant.dst
      .filter(d => d.startsWith('tag:'))
      .flatMap(dst =>
        grant.ip
          .filter(ip => !ip.includes(':') || ip.startsWith('tcp:'))
          .map(ip => `${dst}:${ip.replace(/^tcp:/, '')}`),
      );
    return accept.length ? grant.src.map(src => ({ src, accept })) : [];
  });
}

const q = (s: string) => JSON.stringify(s);
const arr = (xs: string[]) => `[${xs.map(q).join(', ')}]`;

function policyText(
  grants: GeneratedGrant[],
  tagOwners: Record<string, string[]>,
  tests: Array<{ src: string; accept: string[] }>,
  options: RenderOptions,
): string {
  const lines = [
    '// Generated by Backstage (the tailnet-policy backend plugin) from the',
    '// software catalog: one grant per Component that consumes an API with',
    "// specht-labs.de/tailnet-dst, from outside the provider's cluster.",
    '// Do not edit. Change the catalog-info.yaml files instead.',
    `// Compared against ${options.basePolicyUrl}`,
    '{',
    '\t"grants": [',
  ];
  for (const grant of grants) {
    for (const from of grant.from) lines.push(`\t\t// ${from}`);
    lines.push(
      '\t\t{',
      `\t\t\t"src": ${arr(grant.src)},`,
      `\t\t\t"dst": ${arr(grant.dst)},`,
      `\t\t\t"ip":  ${arr(grant.ip)},`,
      '\t\t},',
    );
  }
  lines.push('\t],');
  if (Object.keys(tagOwners).length) {
    lines.push(
      '\t// Tags the grants use that the hand-written policy has no owners for.',
      '\t"tagOwners": {',
    );
    for (const [tag, owners] of Object.entries(tagOwners)) {
      lines.push(`\t\t${q(tag)}: ${arr(owners)},`);
    }
    lines.push('\t},');
  }
  lines.push('\t"tests": [');
  for (const test of tests) {
    lines.push(`\t\t{"src": ${q(test.src)}, "accept": ${arr(test.accept)}},`);
  }
  lines.push('\t],', '}', '');
  return lines.join('\n');
}

function grantNumber(base: Policy, grant: Grant) {
  return (base.grants ?? []).indexOf(grant) + 1;
}

function code(s: string) {
  return `\`${s}\``;
}

function report(
  graph: TailnetGraph,
  grants: GeneratedGrant[],
  tagOwners: Record<string, string[]>,
  base: Policy,
  options: RenderOptions,
) {
  const baseGrants = base.grants ?? [];
  const serviceGrants = baseGrants.filter(isServiceGrant);
  const summary: Rendered['summary'] = {
    grants: grants.length,
    match: 0,
    broad: 0,
    new: 0,
    declared: 0,
    partial: 0,
    missing: 0,
  };

  const generatedRows = grants.map(grant => {
    const flows = flowsOf(grant);
    const exact = new Set<Grant>();
    const broad = new Set<Grant>();
    let status: GrantStatus = 'match';
    for (const flow of flows) {
      const service = serviceGrants.find(g => grantAllows(g, flow));
      if (service) {
        exact.add(service);
        continue;
      }
      const other = baseGrants.find(g => grantAllows(g, flow));
      if (other) {
        broad.add(other);
        if (status === 'match') status = 'broad';
      } else {
        status = 'new';
      }
    }
    summary[status]++;
    const today: Record<GrantStatus, string> = {
      new: '❌ not allowed today',
      broad: `⚠️ only by ${[...broad]
        .map(g => `#${grantNumber(base, g)} ${code(describeGrant(g))}`)
        .join(', ')}`,
      match: `✅ ${[...exact].map(g => `#${grantNumber(base, g)}`).join(', ')}`,
    };
    return `| ${code(describeGrant(grant))} | ${grant.from.join('<br>')} | ${
      today[status]
    } |`;
  });

  const handWrittenRows = serviceGrants.map(grant => {
    const flows = flowsOf(grant);
    const covered = (f: Flow) => grants.some(g => grantAllows(g, f));
    // A bare port allows every protocol; the catalog usually names one.
    const asTcp = (f: Flow) =>
      f.port.proto === '*' &&
      covered({ ...f, port: { ...f.port, proto: 'tcp' } });
    const missing = flows.filter(f => !covered(f));
    let status: DeclaredStatus = 'partial';
    if (!missing.length) status = 'declared';
    else if (missing.length === flows.length && !missing.some(asTcp))
      status = 'missing';
    summary[status]++;
    const describeMissing = (f: Flow) =>
      asTcp(f)
        ? `${code(describeFlow(f))} (declared for tcp only)`
        : code(describeFlow(f));
    const cell: Record<DeclaredStatus, string> = {
      declared: '✅ declared',
      missing: '❌ not in the catalog',
      partial: `⚠️ partly; not declared: ${missing
        .map(describeMissing)
        .join(', ')}`,
    };
    return `| #${grantNumber(base, grant)} | ${code(describeGrant(grant))} | ${
      cell[status]
    } |`;
  });

  const out: string[] = [
    '## Tailnet policy from the catalog (shadow mode)',
    '',
    `${grants.length} grants rendered from ${graph.edges.length} tailnet edges in the catalog, ` +
      `compared with the live policy at ${options.basePolicyUrl}. ` +
      'Nothing is applied: this shows what the catalog would produce, next to what is hand-written today.',
    '',
    '| | |',
    '|---|---:|',
    `| ✅ Generated grants a hand-written service grant already allows | ${summary.match} |`,
    `| ⚠️ Generated grants allowed today only by a broader grant | ${summary.broad} |`,
    `| ❌ Generated grants not allowed today (would widen the policy) | ${summary.new} |`,
    `| Hand-written service grants the catalog fully declares | ${summary.declared} of ${serviceGrants.length} |`,
    '',
    '### Generated grants',
    '',
    '| Grant | From the catalog | Allowed today by |',
    '|---|---|---|',
    ...generatedRows,
    '',
    '### Hand-written service grants',
    '',
    'Grants with tag sources, tag or service destinations and concrete ports: the ones the catalog should produce. ' +
      'Grants for people, zones (`*` ports), wildcards and app capabilities stay hand-written and are not listed.',
    '',
    '| # | Grant | In the catalog |',
    '|---|---|---|',
    ...handWrittenRows,
  ];

  const findings = (
    title: string,
    items: { entity: string; message: string }[],
  ) => {
    if (!items.length) return;
    out.push('', `### ${title}`, '');
    for (const f of items)
      out.push(`- ${code(shortRef(f.entity))}: ${f.message}`);
  };
  // Service-shaped grants to a named host: the catalog can't express those.
  const toHosts = baseGrants.filter(
    g =>
      !g.app &&
      g.src.every(src => src.startsWith('tag:')) &&
      g.dst.some(d => !/^(tag|svc|autogroup):/.test(d) && d !== '*') &&
      grantPorts(g).every(p => !isWildcardPort(p)),
  );
  if (toHosts.length) {
    out.push(
      '',
      '### Not compared: grants to named hosts',
      '',
      'Catalog destinations are tags or Tailscale Services; these stay hand-written until the host gets one.',
      '',
      ...toHosts.map(
        g => `- #${grantNumber(base, g)} ${code(describeGrant(g))}`,
      ),
    );
  }

  findings('Invalid annotations (ignored)', graph.invalid);
  findings(
    'Crossing the tailnet without a tailnet identity',
    graph.missingSource,
  );

  if (Object.keys(tagOwners).length) {
    out.push(
      '',
      '### Tags without owners in the hand-written policy',
      '',
      ...Object.entries(tagOwners).map(
        ([tag, owners]) =>
          `- ${code(tag)}: would be owned by ${owners.map(code).join(', ')}`,
      ),
    );
  }

  if (graph.local.length) {
    out.push(
      '',
      `<details><summary>${graph.local.length} edges inside a cluster (pod network, not the tailnet; Cilium's, later)</summary>`,
      '',
      ...graph.local.map(
        e =>
          `- ${shortRef(e.consumer)} → ${shortRef(e.api)} (${
            parseEntityRef(e.cluster).name
          })`,
      ),
      '',
      '</details>',
    );
  }

  return { text: `${out.join('\n')}\n`, summary };
}

export function renderPolicy(
  graph: TailnetGraph,
  base: Policy,
  options: RenderOptions,
): Rendered {
  const grants = grantsFromGraph(graph);
  const tagOwners = tagOwnersFor(graph, grants, base, options);
  const tests = testsFor(grants);
  const { text, summary } = report(graph, grants, tagOwners, base, options);
  return {
    grants,
    tagOwners,
    tests,
    policyText: policyText(grants, tagOwners, tests, options),
    report: text,
    summary,
  };
}
